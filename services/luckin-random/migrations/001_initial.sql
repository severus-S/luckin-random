PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS migrations(version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS config(id INTEGER PRIMARY KEY CHECK(id=1), json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS secrets(name TEXT PRIMARY KEY, encrypted TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS intents(
 id TEXT PRIMARY KEY, fingerprint TEXT NOT NULL, state TEXT NOT NULL,
 created_at TEXT NOT NULL, json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS events(
 seq INTEGER PRIMARY KEY AUTOINCREMENT, intent_id TEXT NOT NULL,
 at TEXT NOT NULL, state TEXT NOT NULL, detail TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS jobs(id TEXT PRIMARY KEY, json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS job_runs(
 job_id TEXT NOT NULL, slot TEXT NOT NULL, intent_id TEXT NOT NULL,
 PRIMARY KEY(job_id,slot)
);
CREATE TABLE IF NOT EXISTS outbox(
 id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL,
 message TEXT NOT NULL, read INTEGER NOT NULL DEFAULT 0
);
